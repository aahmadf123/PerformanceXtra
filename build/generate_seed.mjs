// Regenerate db/seed_activities.sql from data.js (window.PX_DATA).
//
// data.js is the upstream source of truth for the 190 base activities (itself generated
// from build/PerformanceXtra_Master_Sheet.xlsx via build/generate_data.py). This script
// loads it in a minimal `window` shim, reads PX_DATA, and emits INSERT statements that
// mirror those rows into the D1 `base_activities` table.
//
//   node build/generate_seed.mjs
//   wrangler d1 execute performancextra --file db/seed_activities.sql --remote

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dataPath = resolve(root, "data.js");
const outPath = resolve(root, "db", "seed_activities.sql");

// Evaluate data.js against a fake `window` so we can read PX_DATA without a browser.
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(readFileSync(dataPath, "utf8"), sandbox, { filename: "data.js" });

const data = sandbox.window.PX_DATA;
if (!Array.isArray(data) || !data.length) {
  console.error("Could not read window.PX_DATA from data.js");
  process.exit(1);
}

// SQLite string literal: single quotes are escaped by doubling them.
const sql = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const lines = [
  "-- Generated by build/generate_seed.mjs from data.js — do not edit by hand.",
  "-- Seeds the 190 base activities into the D1 base_activities table.",
  "",
];

data.forEach((activity, i) => {
  const id = activity.id;
  const payload = JSON.stringify(activity);
  lines.push(
    `INSERT OR REPLACE INTO base_activities (id, payload, position) VALUES (${sql(id)}, ${sql(payload)}, ${i});`
  );
});

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`Wrote ${data.length} base activities to ${outPath}`);
